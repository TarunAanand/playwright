/**
 * scripts/lib/templates.js
 *
 * Deterministic source templates used by gen-pom / gen-tests. Everything here is
 * produced locally from the Markdown instructions — no API key, no network. The
 * optional AI refinement pass is applied on top of these templates only when it
 * is explicitly requested and configured.
 */
import path from 'node:path';

const HEADER = 'AUTO-GENERATED by `npm run gen';
const MAINTAINED_NOTE = 'Existing, hand-maintained files are never overwritten — delete this file or pass --force to regenerate.';

function commentBlock(extra = '') {
  return [
    '/**',
    ` * ${HEADER}.`,
    extra ? ` * ${extra}` : null,
    ' * Edit the instruction file under .context/instructions/ and re-run generation instead of',
    ' * hand-editing this scaffold.',
    ' */',
  ].filter(Boolean).join('\n');
}

/** Selector strings in the instructions are written against `page`. */
function locatorLine(selector) {
  const cleaned = selector.replace(/^page\./, '').trim();
  return `page.${cleaned.startsWith('getBy') || cleaned.startsWith('locator') || cleaned.startsWith('xpath=') ? cleaned : `locator(${JSON.stringify(cleaned)})`}`;
}

function gotoPathFromUrl(url) {
  const first = String(url).split(/\s+/)[0];
  return first.startsWith('/') ? first : '/';
}

export function renderPom({ className, instruction, importDepth = 1 }) {
  const baseImport = `${'../'.repeat(importDepth)}base/BasePage.js`;
  const elements = instruction.elements.map((element) =>
    `    this.${element.property} = ${locatorLine(element.selector)};${element.description ? `  // ${element.description}` : ''}`);

  const actions = instruction.actions.map((action) => {
    const [head] = action.signature.split('(');
    const name = /^[A-Za-z_$][\w$]*$/.test(head) ? head : action.method;
    return `  /** ${action.name}${action.note ? ` — ${action.note}` : ''} */\n  async ${name}(...args) {\n    // TODO: implement from the instruction (kept as a scaffold so the class shape compiles).\n    return this;\n  }`;
  });

  return `${commentBlock(MAINTAINED_NOTE)}
import { BasePage } from '${baseImport}';

export class ${className} extends BasePage {
  constructor(page) {
    super(page);
${elements.join('\n')}${elements.length ? '\n' : ''}  }

  /** Navigate to ${instruction.url} */
  async goto() {
    await this.navigate(${JSON.stringify(gotoPathFromUrl(instruction.url))});
    return this;
  }

${actions.join('\n\n')}
}
`;
}

/** Turn the natural-language "Expected" line into the strongest assertion we can
 *  derive without guessing. Returns null when nothing safe can be inferred. */
function deriveAssertion(expected) {
  const urlMatch = /(?:\/[a-z0-9][a-z0-9-]*[a-z0-9-]*)/i.exec(expected.replace(/[a-z]+:\/\//i, ''));
  if (/page (should )?(load|redirect)|url|route/i.test(expected) && urlMatch) {
    return `await assertThat('${escapeText(expected)}', () => expect(page).toHaveURL(/${urlMatch[0].slice(1).replace(/[/\\^$*+?.()|[\]{}]/g, '\\$&')}/));`;
  }
  if (/heading|title/i.test(expected)) {
    return "await assertThat('Heading is visible', () => expect(page.locator('h1')).toBeVisible());";
  }
  if (/error|alert|message/i.test(expected)) {
    return "await assertThat('Error message is visible', () => expect(page.getByRole('alert')).toBeVisible());";
  }
  return null;
}

function escapeText(value) {
  return String(value).replace(/'/g, "\\'").slice(0, 110);
}

export function renderSpec({ feature, resolvedPages, fixtureName = 'base.fixture.js', depthPrefix = '../' }) {
  const imports = [];
  imports.push(`import { test, expect } from '${depthPrefix}fixtures/${fixtureName}';`);
  imports.push(`import { assertThat } from '${depthPrefix}fixtures/expect-helper.js';`);
  imports.push(`import { step } from '${depthPrefix}fixtures/step-runner.js';`);
  imports.push(`import { loadUsers } from '${depthPrefix}fixtures/data-helper.js';`);
  for (const page of resolvedPages) {
    imports.push(`import { ${page.className} } from '${page.importPath}';`);
  }

  const describeBody = feature.tests.map((testCase) => {
    const instances = resolvedPages
      .map((page) => `    const ${lowerFirst(page.className)} = new ${page.className}(page);`)
      .join('\n');
    const steps = testCase.steps.map((line, index) =>
      `    await step(${JSON.stringify(`${index + 1}. ${line}`)}, async () => {\n      // TODO: perform "${line}" using the Page Objects above.\n    });`);
    const assertion = deriveAssertion(testCase.expected);
    const verify = assertion
      ? `    await step('Verify: ${escapeText(testCase.expected)}', async () => {\n      ${assertion}\n    });`
      : `    await step('Verify: ${escapeText(testCase.expected)}', async () => {\n      // TODO: assert "${escapeText(testCase.expected)}"\n    });`;
    return `  test(${JSON.stringify(`${testCase.id} — ${testCase.name}`)}, async ({ page }) => {
${instances ? `${instances}\n\n` : ''}${testCase.precondition ? `    // Precondition: ${testCase.precondition}\n` : ''}${steps.join('\n\n')}${steps.length ? '\n\n' : ''}${verify}
  });`;
  }).join('\n\n');

  return `${commentBlock(`Feature: ${feature.title}`)}
${imports.join('\n')}

const users = loadUsers();

test.describe('${escapeText(feature.title)}', () => {

${describeBody}

});
`;
}

function lowerFirst(value) {
  return value.charAt(0).toLowerCase() + value.slice(1);
}
